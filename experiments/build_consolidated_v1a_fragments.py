# Build consolidated v1a fragment layer from consolidated v1 legacy_core.py.
# Environment: Python 3.12.
# Role: draft output v1a / mechanical modular split builder.

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path

FRAGMENT_FUNCTIONS: tuple[str, ...] = (
    "read_instance",
    "is_station",
    "is_customer",
    "is_pickup",
    "is_delivery",
    "energy_ok_fullbatt",
    "compute_Emin",
    "max_dist",
    "earliest_delivery_possible",
    "best_station_between",
    "strip_stations",
    "cust_locs",
    "compute_T_E_L",
    "compute_distance",
    "dedup_exact",
    "dedup_by_signature",
    "attach_metadata",
    "dominates",
    "filter_by_key",
    "dominance_filter",
    "step",
    "enumerate_base_paths",
    "trim_base_path",
    "enumerate_fragments",
    "compute_onboard_states",
    "extend_all_fragments",
    "stats_frags",
    "stats_ext",
)

SAFE_ASSIGNMENT_NAMES: tuple[str, ...] = (
    "DEBUG",
    "DEBUG_CALLBACK",
    "DEBUG_DIAGNOSTICS",
    "FORCE_CHAIN",
    "RUN_OPTIONA",
    "DIAG_SKELETON",
    "DP_MAX_STATION_VISITS_PER_LEG",
    "DP_MAX_LABELS_PER_NODE",
    "GENERATED",
    "SOURCE_PATH",
    "SOURCE_PATH_POSIX",
    "SOURCE_SHA256",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build consolidated v1a fragment_core.py from consolidated v1 legacy_core.py.")
    parser.add_argument("--core", default="evrp_fragments_consolidated_v1/legacy_core.py")
    parser.add_argument("--output", default="evrp_fragments_consolidated_v1/fragment_core.py")
    return parser.parse_args()


def is_safe_assignment(node: ast.stmt) -> bool:
    if not isinstance(node, ast.Assign):
        return False
    names = [target.id for target in node.targets if isinstance(target, ast.Name)]
    return bool(names) and all(name in SAFE_ASSIGNMENT_NAMES for name in names)


def source_segment(source_text: str, node: ast.AST) -> str:
    segment = ast.get_source_segment(source_text, node)
    if segment is None:
        segment = ast.unparse(node)
    return segment.rstrip() + "\n"


def main() -> None:
    args = parse_args()
    core_path = Path(args.core)
    output_path = Path(args.output)
    if not core_path.exists():
        raise FileNotFoundError(f"Consolidated core not found: {core_path}. Run build_consolidated_v1 first.")

    source_text = core_path.read_text(encoding="utf-8")
    source_sha256 = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
    tree = ast.parse(source_text, filename=str(core_path))

    requested = set(FRAGMENT_FUNCTIONS)
    found: dict[str, ast.AST] = {}
    selected_nodes: list[ast.AST] = []

    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            selected_nodes.append(node)
        elif is_safe_assignment(node):
            selected_nodes.append(node)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in requested:
            selected_nodes.append(node)
            found[node.name] = node

    missing = [name for name in FRAGMENT_FUNCTIONS if name not in found]
    if missing:
        raise RuntimeError("Missing expected fragment functions: " + ", ".join(missing))

    header = (
        '"""Mechanically extracted fragment layer for consolidated v1a.\n\n'
        'Generated by experiments.build_consolidated_v1a_fragments.\n'
        'Source module is evrp_fragments_consolidated_v1/legacy_core.py.\n'
        'Role: generated derived output / mechanical fragment split.\n'
        'Do not edit manually during parity consolidation.\n'
        '"""\n\n'
        'from __future__ import annotations\n\n'
        'FRAGMENT_CORE_GENERATED = True\n'
        f'FRAGMENT_CORE_SOURCE = {str(core_path)!r}\n'
        f'FRAGMENT_CORE_SOURCE_SHA256 = {source_sha256!r}\n\n'
    )

    body_parts: list[str] = []
    for node in selected_nodes:
        text = source_segment(source_text, node)
        if text.strip() == "from __future__ import annotations":
            continue
        # Avoid redefining GENERATED from legacy_core as meaning fragment_core generated.
        if text.startswith("GENERATED ="):
            continue
        body_parts.append(text)
        body_parts.append("\n")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(header + "".join(body_parts), encoding="utf-8")

    manifest = {
        "name": "evrp_fragments_consolidated_v1a_fragment_core",
        "role": "generated derived output / mechanical fragment split",
        "source": str(core_path),
        "source_sha256": source_sha256,
        "output": str(output_path),
        "function_count": len(FRAGMENT_FUNCTIONS),
        "functions": list(FRAGMENT_FUNCTIONS),
    }
    Path("MANIFEST_consolidated_v1a_fragment_core.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
