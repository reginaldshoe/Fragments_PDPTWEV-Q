from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path

FUNCTIONS_IN_SCOPE: tuple[str, ...] = (
    "read_instance", "is_station", "is_customer", "is_pickup", "is_delivery",
    "energy_ok_fullbatt", "compute_Emin", "max_dist", "earliest_delivery_possible",
    "best_station_between", "strip_stations", "cust_locs", "compute_T_E_L",
    "compute_distance", "dedup_exact", "dedup_by_signature", "attach_metadata",
    "dominates", "filter_by_key", "dominance_filter", "print_dp_path_structure",
    "step", "enumerate_base_paths", "trim_base_path", "enumerate_fragments",
    "compute_onboard_states", "extend_all_fragments", "stats_frags", "stats_ext",
    "raw_depot_arcs", "build_network", "dp_leg_frontier_charge_to_full",
    "dp_route_min_dist", "make_gurobi_env", "build_master_model", "callback",
    "extract_routes_from_solution", "route_distance_from_sids", "stitch_sid_sequence",
    "simulate_route",
)

SAFE_ASSIGNMENT_NAMES: tuple[str, ...] = (
    "DEBUG", "DEBUG_CALLBACK", "DEBUG_DIAGNOSTICS", "FORCE_CHAIN", "RUN_OPTIONA",
    "DIAG_SKELETON", "DP_MAX_STATION_VISITS_PER_LEG", "DP_MAX_LABELS_PER_NODE",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build consolidated v1 from ev_fragmentsv3.py.")
    parser.add_argument("--legacy", default="ev_fragmentsv3.py")
    parser.add_argument("--output", default="evrp_fragments_consolidated_v1/legacy_core.py")
    return parser.parse_args()


def resolve_legacy_source(source: str | Path) -> Path:
    raw = Path(source)
    candidates = [raw]
    if raw.suffix == "":
        candidates.append(raw.with_suffix(".py"))
    candidates.append(Path.cwd() / raw.name)
    if raw.suffix == "":
        candidates.append(Path.cwd() / f"{raw.name}.py")
    seen = set()
    for candidate in candidates:
        candidate = candidate.expanduser()
        if candidate in seen:
            continue
        seen.add(candidate)
        if candidate.exists() and candidate.is_file():
            return candidate.resolve()
    raise FileNotFoundError("Legacy source not found. Tried: " + ", ".join(str(c) for c in candidates))


def is_safe_assignment(node: ast.stmt) -> bool:
    if not isinstance(node, ast.Assign):
        return False
    names = [target.id for target in node.targets if isinstance(target, ast.Name)]
    return bool(names) and all(name in SAFE_ASSIGNMENT_NAMES for name in names)


def source_segment(source_text: str, node: ast.AST) -> str:
    segment = ast.get_source_segment(source_text, node)
    if segment is None:
        segment = ast.unparse(node)
    return segment.rstrip() + "\n"


def main() -> None:
    args = parse_args()
    source_path = resolve_legacy_source(args.legacy)
    output_path = Path(args.output)
    source_text = source_path.read_text(encoding="utf-8")
    source_sha256 = hashlib.sha256(source_text.encode("utf-8")).hexdigest()
    tree = ast.parse(source_text, filename=str(source_path))

    requested = set(FUNCTIONS_IN_SCOPE)
    found: dict[str, ast.AST] = {}
    selected_nodes: list[ast.AST] = []

    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            selected_nodes.append(node)
        elif is_safe_assignment(node):
            selected_nodes.append(node)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in requested:
            selected_nodes.append(node)
            found[node.name] = node

    missing = [name for name in FUNCTIONS_IN_SCOPE if name not in found]
    if missing:
        raise RuntimeError("Missing expected legacy functions: " + ", ".join(missing))

    source_path_posix = source_path.as_posix()
    header = (
        '"""Mechanically extracted legacy core for evrp_fragments_consolidated_v1.\n\n'
        'Generated by experiments.build_consolidated_v1.\n'
        'The source path is recorded in SOURCE_PATH and SOURCE_PATH_POSIX below.\n'
        'Role: generated derived output / mechanical extraction.\n'
        'Do not edit manually during parity consolidation.\n'
        '"""\n\n'
        'from __future__ import annotations\n\n'
        'GENERATED = True\n'
        f'SOURCE_PATH = {str(source_path)!r}\n'
        f'SOURCE_PATH_POSIX = {source_path_posix!r}\n'
        f'SOURCE_SHA256 = {source_sha256!r}\n\n'
    )

    body_parts: list[str] = []
    for node in selected_nodes:
        text = source_segment(source_text, node)
        if text.strip() == "from __future__ import annotations":
            continue
        body_parts.append(text)
        body_parts.append("\n")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(header + "".join(body_parts), encoding="utf-8")

    manifest = {
        "name": "evrp_fragments_consolidated_v1_generated_core",
        "role": "generated derived output / mechanical extraction",
        "source": str(source_path),
        "source_posix": source_path_posix,
        "source_sha256": source_sha256,
        "output": str(output_path),
        "function_count": len(FUNCTIONS_IN_SCOPE),
        "functions": list(FUNCTIONS_IN_SCOPE),
    }
    Path("MANIFEST_consolidated_v1_generated_core.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
